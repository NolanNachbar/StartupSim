// One-shot generator for tests/unit/fixtures/golden-replay.json.
// Skipped unless GEN_FIXTURES=1. Run: GEN_FIXTURES=1 npx vitest run tests/unit/gen-fixtures.test.ts
// Regenerating changes what the golden replay test expects. That is a SIM_VERSION bump (see CLAUDE.md).
import { writeFileSync } from "node:fs";
import { describe, it } from "vitest";
import { fromSave, SIM_VERSION } from "../../src/sim/save";
import { view } from "../../src/sim/view";
import { buildHistory, buildReport } from "../../src/sim/report";
import { playFuzz } from "./helpers/fuzz";
import { playValidator } from "./helpers/validator";

const INTERVIEW_ACTIONS = [
  { type: "interview", segment: 0, questions: ["past-behavior", "past-behavior", "past-behavior"] },
  { type: "interview", segment: 1, questions: ["commitment", "commitment", "commitment"] },
  { type: "setPrice", priceCents: 9900 },
  { type: "wait" },
  { type: "interview", segment: 0, questions: ["pitch", "hypothetical", "past-behavior"] },
];

describe("golden replay fixture generator", () => {
  it.runIf(process.env.GEN_FIXTURES === "1")("writes tests/unit/fixtures/golden-replay.json", () => {
    const seed = 42;
    const { run } = playFuzz(seed, 300);
    const fixture = {
      note: "Generated by tests/unit/gen-fixtures.test.ts. Regenerate only with a SIM_VERSION bump.",
      simVersion: SIM_VERSION,
      seed,
      actions: run.actions,
      expected: run.pub,
    };
    writeFileSync(new URL("./fixtures/golden-replay.json", import.meta.url), `${JSON.stringify(fixture, null, 2)}\n`);
  });

  it.runIf(process.env.GEN_FIXTURES === "1")("writes tests/unit/fixtures/golden-replay-interview.json", () => {
    const seed = 339;
    const loaded = fromSave({ simVersion: SIM_VERSION, seed, actions: INTERVIEW_ACTIONS });
    if (!loaded.ok) throw new Error(loaded.reason);
    const fixture = {
      note: "Generated by tests/unit/gen-fixtures.test.ts. Regenerate only with a SIM_VERSION bump.",
      simVersion: SIM_VERSION,
      seed,
      actions: INTERVIEW_ACTIONS,
      expected: view(loaded.run),
    };
    writeFileSync(new URL("./fixtures/golden-replay-interview.json", import.meta.url), `${JSON.stringify(fixture, null, 2)}\n`);
  });

  it.runIf(process.env.GEN_FIXTURES === "1")("writes tests/unit/fixtures/golden-replay-landing.json", () => {
    // The first seed where the scripted validator lands. A landed run proves the game can be won.
    for (let seed = 0; seed < 400; seed++) {
      const { run, actions } = playValidator(seed);
      if (run.pub.status !== "landed") continue;
      const fixture = {
        note: "Generated by tests/unit/gen-fixtures.test.ts (scripted validator policy). Regenerate only with a SIM_VERSION bump.",
        simVersion: SIM_VERSION,
        seed,
        actions,
        expected: run.pub,
      };
      writeFileSync(new URL("./fixtures/golden-replay-landing.json", import.meta.url), `${JSON.stringify(fixture, null, 2)}\n`);
      return;
    }
    throw new Error("no seed landed with the validator policy");
  });

  it.runIf(process.env.GEN_FIXTURES === "1")("writes tests/unit/fixtures/golden-reports.json", async () => {
    // Run after the replay fixtures are written: the reports are built from them.
    const landing = (await import("./fixtures/golden-replay-landing.json")).default;
    const crash = (await import("./fixtures/golden-replay.json")).default;
    const fixture = {
      note: "Generated by tests/unit/gen-fixtures.test.ts from the golden replay fixtures. Regenerate only with a SIM_VERSION bump.",
      simVersion: SIM_VERSION,
      landing: buildReport(buildHistory(landing.seed, landing.actions as never)),
      crash: buildReport(buildHistory(crash.seed, crash.actions as never)),
    };
    writeFileSync(new URL("./fixtures/golden-reports.json", import.meta.url), `${JSON.stringify(fixture, null, 2)}\n`);
  });
});
