// One-shot generator for tests/unit/fixtures/golden-replay.json.
// Skipped unless GEN_FIXTURES=1. Run: GEN_FIXTURES=1 npx vitest run tests/unit/gen-fixtures.test.ts
// Regenerating changes what the golden replay test expects. That is a SIM_VERSION bump (see CLAUDE.md).
import { writeFileSync } from "node:fs";
import { describe, it } from "vitest";
import { SIM_VERSION } from "../../src/sim/save";
import { playFuzz } from "./helpers/fuzz";

describe("golden replay fixture generator", () => {
  it.runIf(process.env.GEN_FIXTURES === "1")("writes tests/unit/fixtures/golden-replay.json", () => {
    const seed = 42;
    const { run } = playFuzz(seed, 300);
    const fixture = {
      note: "Generated by tests/unit/gen-fixtures.test.ts. Regenerate only with a SIM_VERSION bump.",
      simVersion: SIM_VERSION,
      seed,
      actions: run.actions,
      expected: run.pub,
    };
    writeFileSync(new URL("./fixtures/golden-replay.json", import.meta.url), `${JSON.stringify(fixture, null, 2)}\n`);
  });
});
