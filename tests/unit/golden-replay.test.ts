import { describe, expect, it } from "vitest";
import fixture from "./fixtures/golden-replay.json";
import interviewFixture from "./fixtures/golden-replay-interview.json";
import landingFixture from "./fixtures/golden-replay-landing.json";
import reports from "./fixtures/golden-reports.json";
import { buildHistory, buildReport } from "../../src/sim/report";
import { SIM_VERSION, fromSave } from "../../src/sim/save";
import { view } from "../../src/sim/view";

describe("golden replay", () => {
  it("replays the committed seed and action list to the committed final state", () => {
    // protects: a fixed (seed, actions) pair keeps producing the same run; fails_when: any constant,
    // formula, draw key or the hash changes without a SIM_VERSION bump and a regenerated fixture.
    // no_claim: the fixture was generated by this implementation; hand-computed scenarios live in engine.test.ts.
    expect(fixture.simVersion).toBe(SIM_VERSION);
    expect(fixture.actions.length).toBeGreaterThan(5);
    const loaded = fromSave({ simVersion: fixture.simVersion, seed: fixture.seed, actions: fixture.actions });
    expect(loaded.ok).toBe(true);
    if (!loaded.ok) return;
    expect(view(loaded.run)).toEqual(fixture.expected);
    expect(fixture.expected.status).not.toBe("running");
  });

  it("replays the committed interview run to the committed evidence", () => {
    // protects: interview outcomes for a fixed seed stay the same; fails_when: any draw key, constant or
    // table in the signal model changes without a SIM_VERSION bump. no_claim: generated by this implementation.
    expect(interviewFixture.simVersion).toBe(SIM_VERSION);
    const loaded = fromSave({ simVersion: interviewFixture.simVersion, seed: interviewFixture.seed, actions: interviewFixture.actions });
    expect(loaded.ok).toBe(true);
    if (!loaded.ok) return;
    expect(view(loaded.run)).toEqual(interviewFixture.expected);
    expect(interviewFixture.expected.evidence.length).toBe(9);
  });

  it("replays a winning run to the committed final state", () => {
    // protects: the game stays winnable and a won run stays identical; fails_when: any mechanic, constant or
    // draw key in builds, tests, channels or revenue changes without a SIM_VERSION bump.
    expect(landingFixture.simVersion).toBe(SIM_VERSION);
    const loaded = fromSave({ simVersion: landingFixture.simVersion, seed: landingFixture.seed, actions: landingFixture.actions });
    expect(loaded.ok).toBe(true);
    if (!loaded.ok) return;
    expect(view(loaded.run)).toEqual(landingFixture.expected);
    expect(landingFixture.expected.status).toBe("landed");
    expect(landingFixture.expected.endReason).toBe("default-alive");
    expect(landingFixture.expected.hypotheses.some((h) => h.state === "verified")).toBe(true);
  });

  it("writes the same accident reports for the committed landing and crash runs", () => {
    // protects: the report text and classifier stay stable for known runs; fails_when: a rule, a threshold or
    // a sentence changes without a SIM_VERSION bump and a regenerated fixture.
    expect(reports.simVersion).toBe(SIM_VERSION);
    expect(buildReport(buildHistory(landingFixture.seed, landingFixture.actions as never))).toEqual(reports.landing);
    expect(buildReport(buildHistory(fixture.seed, fixture.actions as never))).toEqual(reports.crash);
    expect(reports.crash.probableCause).not.toBeNull();
    expect(reports.crash.numbers.length).toBeGreaterThan(0);
  });
});
