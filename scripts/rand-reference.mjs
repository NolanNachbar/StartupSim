// Independent plain-JavaScript implementation of the keyed draw in docs/specs/M1-simulation-core.md.
// It exists to generate tests/unit/fixtures/rand-golden.json from the spec text, not from src/sim/rng.ts,
// so the TypeScript implementation is checked against a second reading of the algorithm.
// Run: node scripts/rand-reference.mjs > tests/unit/fixtures/rand-golden.json
// Changing the output means changing every saved seed: bump SIM_VERSION and say so in the commit.

function mix(h, v) {
  h = Math.imul(h ^ v, 0x9e3779b1);
  h ^= h >>> 15;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  return h >>> 0;
}

function rand(seed, ...keys) {
  let h = mix(0x811c9dc5, seed >>> 0);
  for (const key of keys) {
    if (typeof key === "number") {
      h = mix(h, 1);
      h = mix(h, key | 0);
    } else {
      h = mix(h, 2);
      h = mix(h, key.length);
      for (let i = 0; i < key.length; i++) h = mix(h, key.charCodeAt(i));
    }
  }
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35);
  h ^= h >>> 16;
  return (h >>> 0) / 0x100000000;
}

const seeds = [0, 1, 42, 0xffffffff];
const keySets = [["world"], ["seg", 0, "pain"], [1]];
const cases = [];
for (const seed of seeds) for (const keys of keySets) cases.push({ seed, keys, value: rand(seed, ...keys) });

console.log(JSON.stringify({ note: "Generated by scripts/rand-reference.mjs from docs/specs/M1-simulation-core.md", cases }, null, 2));
